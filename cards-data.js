function populateEdgeFilter() {
  const select = document.getElementById('filter-edge');
  if (!select) return;
  select.innerHTML = '<option value="">Все грани</option>';
  edges.forEach(edge => {
    const option = document.createElement('option');
    option.value = edge.title;
    option.textContent = edge.title;
    select.appendChild(option);
  });
}

function applyFilter() {
  const edgeFilter = document.getElementById('filter-edge').value;
  const nameFilter = document.getElementById('filter-name').value.toLowerCase().trim();

  const visible = allCards.filter(card => {
    const cardEdge = card.getAttribute('data-edge') || '';
    const cardTitle = card.getAttribute('data-title') || '';
    if (edgeFilter && cardEdge !== edgeFilter) return false;
    if (nameFilter && !cardTitle.toLowerCase().includes(nameFilter)) return false;
    return true;
  });

  layoutCards(visible);   // пересобираем раскладку только из видимых

  const info = document.getElementById('filter-info');
  if (info) {
    info.innerHTML = visible.length
      ? `Найдено карточек: <b>${visible.length}</b>`
      : `Ничего не найдено`;
  }
}

function resetFilter() {
  document.getElementById('filter-edge').value = '';
  document.getElementById('filter-name').value = '';
  layoutCards(allCards);  // возвращаем полную колоду
  const info = document.getElementById('filter-info');
  if (info) info.innerHTML = '';
}

