const pagesContainer = document.getElementById('pages');
const allCards = [];   // все карточки в порядке рендера
let wmCounter = 1;

function createPage() {
  const page = document.createElement('div');
  page.className = 'page';
  pagesContainer.appendChild(page);
  return page;
}

// Создаёт карточку, красит категорию, сохраняет в allCards
function buildCard(html, category) {
  const cardDiv = document.createElement('div');
  cardDiv.innerHTML = html;
  const card = cardDiv.firstElementChild;

  const isLightTheme = document.getElementById('theme-css').href.includes('light');
  card.style.setProperty('--category-color',
    isLightTheme ? (categoryPatterns[category] || '#000')
                 : (categoryColors[category] || '#5c1a1a'));

  allCards.push(card);
  return card;
}

function templatePerk(edge, perk) {
  return `
      <div class="card" data-edge="${edge.title}" data-title="${perk.title}">
        <div class="watermark">${wmCounter}</div>
        <div class="card-header">
          <div class="card-tag">${edge.tag}</div>
          <h1 class="card-title">${perk.title}</h1>
          <div class="card-subtitle">${perk.sub}</div>
        </div>
        <div class="card-body">
          <div class="flavor">${perk.flavor}</div>
          <p class="mechanics">Механика:</p>
          <p>${perk.mech}</p>
        </div>
      </div>`;
}

// ============================================================
// РАСКЛАДКА КАРТОЧЕК ПО СТРАНИЦАМ (главная функция)
// ============================================================
function layoutCards(cards) {
  pagesContainer.innerHTML = '';   // полностью очищаем старые страницы
  let page = null;
  let slot = 0;                    // 0..8 в рамках страницы

  const ensurePage = () => {
    page = createPage();
    slot = 0;
  };

  cards.forEach(card => {
    const isWide = card.classList.contains('card-wide');

    if (isWide) {
      if (!page) ensurePage();
      // широкая карточка должна начинаться с начала строки и занимать 2 слота
      while (slot % 3 !== 0 || slot + 2 > 9) {
        slot++;
        if (slot >= 9) ensurePage();
      }
      page.appendChild(card);
      slot += 2;
    } else {
      if (!page || slot >= 9) ensurePage();
      page.appendChild(card);
      slot++;
    }
  });
}

